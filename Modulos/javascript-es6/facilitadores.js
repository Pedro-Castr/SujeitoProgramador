// Includes - retorna verdadeiro ou falso se existe ou não no array
let nomes = ["Matheus", "Lucas", "Pedro"];
console.log(nomes.includes("Pedro"));

// StartsWith - retorna verdadeiro ou falso se começa ou não com o valor passado
let texto = "Luiza";
console.log(texto.startsWith("L"));

// EndsWith - retorna verdadeiro ou falso se termina ou não com o valor passado
let nome = "Junior";
console.log(nome.endsWith("or"));
